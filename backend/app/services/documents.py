"""Storing patient files on disk, checking what they really are, thumbnails and signed links.

Files are never served from a public folder. The browser gets a short-lived signed link
(HMAC with the JWT secret) so <img> tags work without exposing the login token.
"""

import base64
import hashlib
import hmac
import io
import logging
import os
import time
import uuid
from dataclasses import dataclass
from pathlib import Path

from app.core.config import get_settings

log = logging.getLogger("dentassist.documents")

LINK_SECONDS = 15 * 60
THUMB_SIZE = (360, 360)


@dataclass
class Detected:
    content_type: str
    extension: str
    is_image: bool


def detect(data: bytes) -> Detected | None:
    """Identify a file by its first bytes, never by its name or the browser's claim."""
    if data.startswith(b"\xff\xd8\xff"):
        return Detected("image/jpeg", "jpg", True)
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return Detected("image/png", "png", True)
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return Detected("image/webp", "webp", True)
    if data.startswith(b"%PDF-"):
        return Detected("application/pdf", "pdf", False)
    if len(data) > 132 and data[128:132] == b"DICM":
        return Detected("application/dicom", "dcm", False)
    return None


def _root() -> Path:
    root = Path(get_settings().upload_dir).resolve()
    root.mkdir(parents=True, exist_ok=True)
    return root


def _path(key: str) -> Path:
    root = _root()
    p = (root / key).resolve()
    if root not in p.parents:  # keys are generated by us, but never trust a path
        raise ValueError("Invalid storage key")
    return p


def save(data: bytes, patient_id: str, ext: str) -> str:
    safe_patient = "".join(c for c in patient_id if c.isalnum() or c in "-_")[:64] or "unknown"
    key = f"{safe_patient}/{time.strftime('%Y/%m')}/{uuid.uuid4().hex}.{ext}"
    p = _path(key)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".part")
    tmp.write_bytes(data)
    os.replace(tmp, p)
    return key


def read(key: str) -> bytes:
    return _path(key).read_bytes()


def exists(key: str) -> bool:
    try:
        return _path(key).is_file()
    except ValueError:
        return False


def remove(key: str | None) -> None:
    if not key:
        return
    try:
        _path(key).unlink(missing_ok=True)
    except (ValueError, OSError):
        log.warning("Could not remove %s", key)


def image_info_and_thumbnail(data: bytes, patient_id: str) -> tuple[int | None, int | None, str | None]:
    """(width, height, thumbnail key). Works without Pillow, just without thumbnails."""
    try:
        from PIL import Image, ImageOps
    except ImportError:
        return None, None, None
    try:
        with Image.open(io.BytesIO(data)) as im:
            im = ImageOps.exif_transpose(im)
            width, height = im.size
            thumb = im.convert("RGB")
            thumb.thumbnail(THUMB_SIZE)
            buf = io.BytesIO()
            thumb.save(buf, "JPEG", quality=82)
            return width, height, save(buf.getvalue(), patient_id, "jpg")
    except Exception:  # noqa: BLE001  (a broken image still gets stored, just without a preview)
        log.exception("Thumbnail failed")
        return None, None, None


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# ---------------------------------------------------------------------------
# Signed links
# ---------------------------------------------------------------------------

def _sig(doc_id: str, variant: str, expires: int) -> str:
    secret = get_settings().jwt_secret_key.encode()
    mac = hmac.new(secret, f"doc:{doc_id}:{variant}:{expires}".encode(), hashlib.sha256).digest()
    return base64.urlsafe_b64encode(mac[:18]).decode().rstrip("=")


def signed_query(doc_id: str, variant: str = "file", seconds: int = LINK_SECONDS) -> str:
    expires = int(time.time()) + seconds
    return f"v={variant}&e={expires}&s={_sig(doc_id, variant, expires)}"


def check_signature(doc_id: str, variant: str, expires: int, signature: str) -> bool:
    if expires < time.time():
        return False
    return hmac.compare_digest(_sig(doc_id, variant, expires), signature or "")
